"""Export learned rules to the tools teams already run, so piiguard can be adopted as a layer, not a replacement.

Two targets:

* Presidio. ``presidio_yaml`` writes the no-code recognizer file that ``RecognizerRegistry.add_recognizers_from_yaml``
  loads. ``presidio_recognizers`` returns live ``PatternRecognizer`` objects that also carry piiguard's validators
  (Luhn, decode-then-recheck), which a YAML file cannot express.
* NeMo Guardrails. ``guardrails_config`` writes the ``rails.config.sensitive_data_detection`` block for config.yml,
  using the built-in ``mask sensitive data`` / ``detect sensitive data`` flows. No code needed on the Guardrails side.

Rules with a validator are exported to the no-code formats only when ``include_validated`` is set, because without the
validator they over-match (any 16 digits for a card rule, any base64 blob for a decoder rule). The Python Presidio
path keeps them, with the validator attached.
"""
from __future__ import annotations

import re
from typing import Optional

import regex
import yaml

from .pii.rules import RuleSet

DEFAULT_SCORE = 0.85  # above both Presidio's and NeMo Guardrails' default thresholds
_ENTITY_OK = re.compile(r"[^A-Z0-9_]+")


def entity_name(rule_name: str, prefix: str = "PIIGUARD_") -> str:
    return prefix + (_ENTITY_OK.sub("_", rule_name.upper()).strip("_") or "RULE")


def _flags(rule) -> int:
    # piiguard compiles case-sensitively unless ignore_case is set; Presidio defaults to IGNORECASE|DOTALL|MULTILINE,
    # which would change what a learned rule matches. Pin the flags so the exported rule behaves identically.
    return int(regex.IGNORECASE) if rule.regex.flags & regex.IGNORECASE else 0


def _split(rules: RuleSet, include_validated: bool):
    kept, skipped = [], []
    for r in rules.rules:
        (kept if (not r.validator or include_validated) else skipped).append(r)
    return kept, skipped


def presidio_dicts(rules: RuleSet, prefix: str = "PIIGUARD_", score: float = DEFAULT_SCORE,
                   include_validated: bool = False, language: str = "en") -> tuple[list[dict], list[str]]:
    """One recognizer dict per rule (Presidio's serialized PatternRecognizer form) and the names of skipped rules."""
    kept, skipped = _split(rules, include_validated)
    out = []
    for r in kept:
        out.append({
            "name": f"piiguard_{r.name}",
            "supported_language": language,
            "supported_entity": entity_name(r.name, prefix),
            "global_regex_flags": _flags(r),
            "patterns": [{"name": r.name, "regex": r.pattern, "score": score}],
        })
    return out, [r.name for r in skipped]


def _header(rules: RuleSet, skipped: list[str]) -> str:
    lines = [f"# Generated by `piiguard export` from guard/rules.yaml version {rules.version}. Do not edit by hand;",
             "# re-export after each accepted generation so the reviewed git diff stays the source of truth."]
    if skipped:
        lines.append("# Skipped (need a validator that YAML cannot express; use piiguard.export.presidio_recognizers): "
                     + ", ".join(skipped))
    return "\n".join(lines) + "\n"


def presidio_yaml(rules: RuleSet, **kw) -> str:
    recs, skipped = presidio_dicts(rules, **kw)
    return _header(rules, skipped) + yaml.safe_dump({"recognizers": recs}, sort_keys=False, allow_unicode=True, width=1000)


def guardrails_config(rules: RuleSet, sources: tuple[str, ...] = ("input", "output"),
                      extra_entities: Optional[list[str]] = None, score_threshold: float = 0.4, **kw) -> str:
    """The ``rails:`` block for a NeMo Guardrails config.yml. Pair it with the built-in flows, e.g.
    ``input: flows: [mask sensitive data on input]``."""
    recs, skipped = presidio_dicts(rules, **kw)
    entities = [r["supported_entity"] for r in recs] + list(extra_entities or [])
    sdd: dict = {"recognizers": recs}
    for s in sources:
        sdd[s] = {"score_threshold": score_threshold, "entities": entities}
    flows = {s: {"flows": [f"mask sensitive data on {s}"]} for s in sources if s in ("input", "output")}
    doc = {"rails": {"config": {"sensitive_data_detection": sdd}, **flows}}
    return _header(rules, skipped) + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=1000)


def presidio_recognizers(rules: RuleSet, prefix: str = "PIIGUARD_", score: float = DEFAULT_SCORE, language: str = "en"):
    """Live Presidio recognizers with piiguard's validators attached. Add them with ``analyzer.registry.add_recognizer``
    or pass them as ``ad_hoc_recognizers``."""
    from presidio_analyzer import Pattern, PatternRecognizer

    class PiiguardRecognizer(PatternRecognizer):
        def __init__(self, rule):
            self._rule = rule
            super().__init__(supported_entity=entity_name(rule.name, prefix), name=f"piiguard_{rule.name}",
                             supported_language=language, patterns=[Pattern(rule.name, rule.pattern, score)],
                             global_regex_flags=_flags(rule))

        def validate_result(self, pattern_text: str):
            if not self._rule.validator:
                return None
            # False drops the match (Presidio sets MIN_SCORE); True keeps it at full confidence
            return bool(self._rule.validate(pattern_text, rules))

    return [PiiguardRecognizer(r) for r in rules.rules]
